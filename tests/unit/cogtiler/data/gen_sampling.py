"""Reference data for the RasterIO emulation of the COG tiler (raster_io.h), made with GDAL.

Writes sampling.tif: an EPSG:3857 tiled GeoTIFF, 2 x UInt16, 1000 x 700, 256 px tiles, DEFLATE +
predictor 2, overviews 2 / 4 / 8 whose pixels encode where they are: band 1 = x | level << 12,
band 2 = y | level << 12 (level 0 = full resolution). GDAL's nearest RasterIO of a window into a
buffer then tells exactly which level and which pixels it read; sampling.inc records that for
many windows (edge cases and random ones) as the level and an FNV-1a 64 hash of the columns and
of the rows (int32 values), and the unit test checks PlanRead() against it.

    python3 -I tests/unit/cogtiler/data/gen_sampling.py tests/unit/cogtiler/data
(system GDAL python bindings; GDAL_PAM_ENABLED=NO)
"""
import os
import random
import sys

import numpy as np
from osgeo import gdal

gdal.UseExceptions()


def main():
    out = sys.argv[1]
    os.environ["GDAL_PAM_ENABLED"] = "NO"
    gdal.SetConfigOption("GDAL_PAM_ENABLED", "NO")
    W, H = 1000, 700
    path = os.path.join(out, "sampling.tif")
    tmp = "/vsimem/sampling.tif"
    drv = gdal.GetDriverByName("GTiff")
    ds = drv.Create(tmp, W, H, 2, gdal.GDT_UInt16,
                    ["TILED=YES", "BLOCKXSIZE=256", "BLOCKYSIZE=256", "COMPRESS=DEFLATE", "PREDICTOR=2"])
    ds.SetGeoTransform([-10240777.0, 0.25, 0, 5916486.0, 0, -0.25])
    ds.SetProjection("EPSG:3857")

    def fill(band, w, h, level):
        xs = np.arange(w, dtype=np.uint16) | np.uint16(level << 12)
        ys = np.arange(h, dtype=np.uint16) | np.uint16(level << 12)
        band.GetBand if False else None
        return np.broadcast_to(xs, (h, w)).copy(), np.broadcast_to(ys[:, None], (h, w)).copy()

    a, b = fill(None, W, H, 0)
    ds.GetRasterBand(1).WriteArray(a)
    ds.GetRasterBand(2).WriteArray(b)
    ds.BuildOverviews("NEAREST", [2, 4, 8])
    for lvl in range(3):
        o1 = ds.GetRasterBand(1).GetOverview(lvl)
        o2 = ds.GetRasterBand(2).GetOverview(lvl)
        a, b = fill(None, o1.XSize, o1.YSize, lvl + 1)
        o1.WriteArray(a)
        o2.WriteArray(b)
    ds = None
    gdal.Translate(path, tmp, creationOptions=["TILED=YES", "BLOCKXSIZE=256", "BLOCKYSIZE=256", "COMPRESS=DEFLATE",
                                               "PREDICTOR=2", "COPY_SRC_OVERVIEWS=YES"])
    gdal.Unlink(tmp)

    ds = gdal.Open(path)
    sizes = [(W, H)] + [(ds.GetRasterBand(1).GetOverview(i).XSize, ds.GetRasterBand(1).GetOverview(i).YSize)
                        for i in range(ds.GetRasterBand(1).GetOverviewCount())]
    rnd = random.Random(7)
    cases = [(0, 0, W, H, 256, 256), (0, 0, W, H, 250, 175), (0, 0, W, H, 125, 88), (0, 0, 512, 512, 256, 256),
             (0, 0, 512, 512, 64, 64), (100, 100, 300, 300, 256, 256), (3, 5, 7, 9, 256, 256),
             (999, 699, 1, 1, 256, 256), (0, 0, 1000, 1, 256, 1), (0, 0, 1, 700, 1, 256), (10, 20, 600, 30, 200, 10),
             (10, 20, 30, 600, 10, 200), (0, 0, 1000, 700, 1000, 700), (500, 300, 256, 256, 256, 256),
             (1, 1, 998, 698, 333, 233), (0, 0, 1000, 700, 1, 1), (17, 3, 800, 600, 256, 192)]
    while len(cases) < 400:
        w = rnd.randint(1, W)
        h = rnd.randint(1, H)
        x = rnd.randint(0, W - w)
        y = rnd.randint(0, H - h)
        if rnd.random() < 0.5:
            bw = rnd.choice([256, 128, 512, 37, 255, 257])
            bh = rnd.choice([256, 128, 512, 37, 255, 257, bw])
        else:
            f = rnd.choice([0.3, 0.45, 0.5, 0.55, 0.8, 0.9, 1.0, 1.7, 2.0, 2.4, 3.9, 4.0, 4.1, 7.0, 8.0, 9.5, 16.0])
            bw = max(1, int(w / f))
            bh = max(1, int(h / f))
        cases.append((x, y, w, h, bw, bh))
    def fnv(values):
        h = 1469598103934665603
        for v in values:
            for k in range(4):
                h ^= (v >> (8 * k)) & 0xFF
                h = (h * 1099511628211) & 0xFFFFFFFFFFFFFFFF
        return h

    lines = ["// Generated by gen_sampling.py (GDAL %s). Do not edit." % gdal.__version__,
             "// {x, y, w, h, bufW, bufH, level, fnv(cols), fnv(rows), cols[0], cols[last], rows[0], rows[last]}"]
    for (x, y, w, h, bw, bh) in cases:
        a = np.frombuffer(ds.GetRasterBand(1).ReadRaster(x, y, w, h, bw, bh, gdal.GDT_UInt16), dtype=np.uint16)
        b = np.frombuffer(ds.GetRasterBand(2).ReadRaster(x, y, w, h, bw, bh, gdal.GDT_UInt16), dtype=np.uint16)
        a = a.reshape(bh, bw)
        b = b.reshape(bh, bw)
        levels = set((a >> 12).ravel().tolist()) | set((b >> 12).ravel().tolist())
        assert len(levels) == 1, levels
        level = levels.pop()
        cols = (a[0] & 0xFFF).tolist()
        rows = (b[:, 0] & 0xFFF).tolist()
        assert ((a & 0xFFF) == np.array(cols)[None, :]).all() and ((b & 0xFFF) == np.array(rows)[:, None]).all()
        lines.append("{%d, %d, %d, %d, %d, %d, %d, 0x%016xull, 0x%016xull, %d, %d, %d, %d}," % (
            x, y, w, h, bw, bh, level, fnv(cols), fnv(rows), cols[0], cols[-1], rows[0], rows[-1]))
    with open(os.path.join(out, "sampling.inc"), "w") as f:
        f.write("\n".join(lines) + "\n")
    print("sizes", sizes, "cases", len(cases), "file", os.path.getsize(path))


if __name__ == "__main__":
    main()
