def main():
    src = open(sys.argv[1], encoding="latin-1").read()
    m = re.search(r"unsigned char pestel_shades\[\]\s*=\s*\{(.*?)\};", src, re.S)
    if not m:
        sys.exit("pestel_shades not found")
    data = bytes(int(t, 0) for t in m.group(1).replace("\n", " ").split(",") if t.strip())
    im = Image.open(io.BytesIO(data))
    if im.mode != "RGB" or im.size != (256, 1):
        sys.exit("unexpected ramp image %s %s" % (im.mode, im.size))
    px = [im.getpixel((i, 0)) for i in range(256)]
    print("// Generated by gen_pestel_shades.py from PDAL 2.10.1 filters/ColorInterpRamps.hpp (pestel_shades,")
    print("// a 256 x 1 RGB PNG). Do not edit. The ramp data comes from PDAL, under this licence:")
    print("//")
    for line in LICENCE.strip("\n").split("\n"):
        print(("// " + line).rstrip())
    print("//")
    for i in range(0, 256, 4):
        print("    " + " ".join("{%d, %d, %d}," % p for p in px[i:i + 4]))


if __name__ == "__main__":
    main()
