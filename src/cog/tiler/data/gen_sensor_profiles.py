"""Generates sensor_profiles.inc from DroneDB's data/sensor-profiles.json (MPL-2.0, DroneDB
contributors; the same licence as this project), so the tiler needs no JSON parser at run time.

    python3 -I src/cog/tiler/data/gen_sensor_profiles.py /mnt/data/repos/DroneDB/data/sensor-profiles.json \
        > src/cog/tiler/data/sensor_profiles.inc
"""
import json
import sys


def s(v):
    return json.dumps(v if v is not None else "")


def main():
    path = sys.argv[1]
    with open(path, encoding="utf-8") as f:
        d = json.load(f)
    out = []
    out.append("// Generated by gen_sensor_profiles.py from DroneDB data/sensor-profiles.json (version %s)." % d.get("version"))
    out.append("// Source: https://github.com/DroneDB/DroneDB (MPL-2.0). Do not edit.")
    out.append("// clang-format off")
    for p in d["profiles"]:
        det = p["detection"]
        pats = ", ".join(s(x) for x in det.get("metadataPatterns", []))
        bands = ", ".join("{%d, %s}" % (b["index"], s(b["name"])) for b in p["bands"])
        presets = []
        for r in p["presets"]:
            bm = r.get("bandMapping", {"r": 1, "g": 2, "b": 3})
            presets.append("{%s, %s, {%d, %d, %d}, %s, %s, %s}" % (
                s(r["id"]), s(r.get("type", "bands")), bm["r"], bm["g"], bm["b"],
                "true" if r.get("isDefault", False) else "false", s(r.get("formula", "")), s(r.get("colormap", ""))))
        out.append("{%s, %s, %s, %d, %s, {%s}, %d,\n  {%s},\n  {%s}}," % (
            s(p["id"]), s(p["name"]), s(p["sensorCategory"]), det["bandCount"], s(det.get("dataType", "")), pats,
            det.get("priority", 0), bands, ",\n   ".join(presets)))
    out.append("// clang-format on")
    print("\n".join(out))


if __name__ == "__main__":
    main()
